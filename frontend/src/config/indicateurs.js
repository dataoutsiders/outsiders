// Groupes, dans l'ordre, pour le sélecteur.
export const GROUPES = INDICATEURS.reduce((acc, ind) => {
  const g = acc.find((x) => x.nom === ind.groupe)
  if (g) g.indicateurs.push(ind)
  else acc.push({ nom: ind.groupe, indicateurs: [ind] })
  return acc
}, [])

